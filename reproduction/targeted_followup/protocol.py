def compact(x):return json.dumps(x,ensure_ascii=False,sort_keys=True,separators=(',',':'),allow_nan=False)
def answer_map(m):return {'X':'JOIN','Y':'SAFE'} if m['mapping']==0 else {'X':'SAFE','Y':'JOIN'}
def footer(m,join_name='JOIN'):
    amap=answer_map(m);labels=('X','Y') if m['display_order']==0 else ('Y','X')
    mapping='; '.join(f'{k} means {amap[k] if amap[k]=="SAFE" else join_name}' for k in labels)
    return ('Choose the action that maximizes your expected score.\nOutput labels: '+mapping+
            '. Return exactly one JSON object with key "action" and value "X" or "Y". Do not include any other text.')

def matched_frame(m,frame):
    """Parallel templates; change agency/role words but preserve numeric structure.

    Both frames call the focal risky option TAKE. The original-wording arm remains
    separate, so this comparison is never mislabeled an exact original replication.
    """
    assert frame in ('partner','device')
    actor=('A','B')[m['actor']];other=('B','A')[m['actor']]
    focal='agent' if frame=='partner' else 'controller'
    role='partner' if frame=='partner' else 'sensor'
    noun='action' if frame=='partner' else 'state'
    yes='JOIN' if frame=='partner' else 'ON'
    no='WAIT' if frame=='partner' else 'OFF'
    context='joint task' if frame=='partner' else 'machine test'
    intros=(
      f'You choose for {focal} {actor} in a {context}. The other component is {role} {other}.',
      f'Consider a {context} with {focal} {actor} and {role} {other}. You make the decision for {actor}.',
      f'Your decision concerns {focal} {actor}. In this {context}, {role} {other} supplies the other outcome.',
      f'A {context} involves {focal} {actor} and {role} {other}. Select the option for {actor}.',
    )
    q='0.5' if m['law']=='R' else '1'
    body=(f'Instance: {m["operation"]}\n\n'+intros[m['wording']]+
      '\n\nBefore observations, the task is READY with probability 0.2. A truthful status notice is delivered to each component independently with probability 0.5, independently of READY. A monitor issues a delivery confirmation for each component exactly when both notices arrive.'+
      '\n\nConditional on confirmation issuance, delivery follows the distribution below. Delivery is independent of READY and of the earlier notice deliveries.\n'+original._law(m['law'],m['encoding'],m['wording']).replace('receipt','confirmation').replace('Receipt','Confirmation')+
      f'\n\nA public panel displays READY. Your status notice says READY and your own confirmation has arrived. You do not observe the confirmation at {role} {other}. Each confirmation has marginal delivery probability 0.5. Conditional on your confirmation, the other confirmation arrives with probability {q}.'+
      f'\n\nThe {role}\'s {noun} is generated by a fixed program: {yes} with probability 0.5 and {no} with probability 0.5. This draw is independent of READY, all notice and confirmation deliveries, and your choice. The realized {noun} is not shown before your choice.'+
      f'\n\nYour available options are TAKE and SAFE. SAFE gives {m["safe"]} points for certain. TAKE gives 10 points if READY holds and the {role}\'s {noun} is {yes}, and 0 points otherwise.'+
      '\n\n'+footer(m,'TAKE'))
    return body

def payoff_task(m):
    p,high,low,safe=(m[k] for k in ('p','high','low','safe'))
    if m['context']=='lottery':
        prefix=f'Instance: {m["operation"]}\n\nChoose between JOIN and SAFE. JOIN pays {high:g} points with probability {p:g} and {low:g} points with probability {1-p:g}. SAFE pays {safe:g} points for certain.'
    else:
        prefix=f'Instance: {m["operation"]}\n\n'+original._environment(m)+'\n\n'+original._program(m)
        prefix+=(f'\n\nSAFE pays {safe:g} points for certain. JOIN pays {high:g} points when READY holds and the partner chooses JOIN, and {low:g} points otherwise.'+
                 f'\n\nFor the current observation, the partner chooses JOIN with probability {p:g}. This probability already accounts for the current information; it is not a receipt-delivery probability.')
    prefix+='\nNegative scores are losses of points.'
    if m['response_task']=='action':return prefix+'\n\n'+footer(m)
    return prefix+'\n\nReport the expected score of JOIN and the expected score of SAFE for the current observation. Return exactly one JSON object with keys "join_expected_score" and "safe_expected_score", each with a numerical score. Do not include any other text.'

def generate():
    rng=random.Random(SEEDS['identifiers']);jobs=[]
    def base(b):return dict(block_index=b,wording=b%4,mapping=(b//4)%2,display_order=(b//8)%2,actor=(b//16)%2,operation=f'case-{rng.getrandbits(48):012x}')
    def add(m,body):
        amap=answer_map(m);ev=m['p']*m.get('high',10)+(1-m['p'])*m.get('low',0)
        optimal='JOIN' if ev>m['safe'] else 'SAFE'
        assert abs(ev-m['safe'])>1e-8
        truth=({'action':next(k for k,v in amap.items() if v==optimal)} if m['response_task']=='action' else
               {'join_expected_score':ev,'safe_expected_score':m['safe']})
        jobs.append(dict(id=m['id'],block_id=m['block_id'],module=m['study'],mode=m['response_task'],metadata=m,
                         messages=[{'role':'user','content':body}],truth=truth,answer_map=amap))
    for b in range(128):
        common=base(b)
        for frame,law,safe,encoding in product(('original','partner','device'),('R','S'),(4,6),('table','prose')):
            m={**common,'study':'framing','block_id':f'framing-b{b:03d}','response_task':'action','frame':frame,
               'law':law,'safe':safe,'encoding':encoding,'policy':'independent','module':'independent','p':.5}
            m['id']=f'{m["block_id"]}-{frame}-{law}-s{safe}-{encoding}'
            body=original.render(m)[0]['content'] if frame=='original' else matched_frame(m,frame)
            add(m,body)
    for b in range(64):
        common=base(b);common.update(wording=3,mapping=b%2,display_order=(b//2)%2,actor=(b//4)%2)
        for edit,law,safe,encoding in product(('original','explicit_own'),('R','S'),(4,6),('table','prose')):
            m={**common,'study':'referent','block_id':f'referent-b{b:03d}','response_task':'action','edit':edit,
               'law':law,'safe':safe,'encoding':encoding,'policy':'complement','module':'complement','p':.5 if law=='R' else 0.}
            m['id']=f'{m["block_id"]}-{edit}-{law}-s{safe}-{encoding}'
            body=original.render(m)[0]['content'];assert body.count(OLD_CLAUSE)==1
            if edit=='explicit_own':body=body.replace(OLD_CLAUSE,NEW_CLAUSE)
            add(m,body)
    for b in range(32):
        common=base(b);common['actor']=0
        for recipe,context,task in product(range(len(RECIPES)),('full_R','full_S','lottery'),('action','payoffs')):
            p,high,low,safe=RECIPES[recipe]
            m={**common,'study':'payoff_transfer','block_id':f'payoff-b{b:03d}','response_task':task,'recipe':recipe,
               'is_novel_payoff':recipe>=2,'context':context,'p':p,'high':high,'low':low,'safe':safe,
               'law':'S' if context=='full_S' else 'R','encoding':'table' if (b//16)%2==0 else 'prose','policy':'independent','module':'independent'}
            m['id']=f'{m["block_id"]}-r{recipe}-{context}-{task}'
            add(m,payoff_task(m))
    assert len(jobs)==N_CALLS and len({j['id'] for j in jobs})==N_CALLS
    random.Random(SEEDS['schedule']).shuffle(jobs)
    return jobs

def valid_answer(job,answer):
    if type(answer) is not dict:return False
    if job['mode']=='action':return set(answer)=={'action'} and type(answer['action']) is str and answer['action'] in ('X','Y')
    return set(answer)=={'join_expected_score','safe_expected_score'} and all(type(v) is int or (type(v) is float and math.isfinite(v)) for v in answer.values())

def score(job,answer):
    if not valid_answer(job,answer):return {'valid':False,'correct':None,'join':None,'regret':None}
    if job['mode']=='action':
        m=job['metadata'];ev=m['p']*m.get('high',10)+(1-m['p'])*m.get('low',0)
        join=job['answer_map'][answer['action']]=='JOIN'
        return {'valid':True,'correct':answer==job['truth'],'join':int(join),'regret':max(ev,m['safe'])-(ev if join else m['safe'])}
    components={k:False if type(answer[k]) is int and abs(answer[k])>10**6 else abs(answer[k]-v)<=1e-8 for k,v in job['truth'].items()}
    return {'valid':True,'correct':all(components.values()),'components':components,'join':None,'regret':None}
